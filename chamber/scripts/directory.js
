const memberList = document.getElementById('member-list');
const viewButtons = document.querySelectorAll('.view-button');

let members = [];
let activeView = 'grid';

const membershipLabels = {
  1: 'Member',
  2: 'Silver',
  3: 'Gold'
};

function getMembershipLabel(level) {
  return membershipLabels[level] || 'Member';
}

function renderMembers(view = activeView) {
  activeView = view;

  if (!memberList) {
    return;
  }

  memberList.className = view === 'list' ? 'member-list' : 'member-grid';

  if (!members.length) {
    memberList.innerHTML = '<p class="member-empty">No members available.</p>';
    return;
  }

  memberList.innerHTML = members
    .map((member) => {
      const label = getMembershipLabel(member.membershipLevel);
      const website = member.website.startsWith('http') ? member.website : `https://${member.website}`;

      return `
        <article class="member-card">
          <img src="images/${member.image}" alt="${member.company} logo" class="member-image">
          <div class="member-details">
            <div class="member-header">
              <h3>${member.company}</h3>
              <span class="membership-badge membership-${member.membershipLevel}">${label}</span>
            </div>
            <p class="member-category">${member.category}</p>
            <p><strong>Address:</strong> ${member.address}</p>
            <p><strong>Phone:</strong> ${member.phone}</p>
            <p>
              <strong>Website:</strong>
              <a href="${website}" target="_blank" rel="noreferrer">${member.website}</a>
            </p>
            <p>${member.description}</p>
          </div>
        </article>
      `;
    })
    .join('');
}

async function loadMembers() {
  try {
    const response = await fetch('data/members.json');

    if (!response.ok) {
      throw new Error(`Unable to load member data: ${response.status}`);
    }

    members = await response.json();
    renderMembers(activeView);
  } catch (error) {
    console.error(error);
    if (memberList) {
      memberList.innerHTML = '<p class="member-empty">Member information is temporarily unavailable.</p>';
    }
  }
}

viewButtons.forEach((button) => {
  button.addEventListener('click', () => {
    const selectedView = button.dataset.view;

    viewButtons.forEach((item) => item.classList.toggle('active', item === button));
    renderMembers(selectedView);
  });
});

loadMembers();
